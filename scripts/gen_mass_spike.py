#!/usr/bin/env python3
"""Writes samples/mass_spike.usda, the curve-mass-field spike's scene.

Two sheets of straight strands cross along the line x = 0: sheet A lies in the
plane z = +0.25 x with its strands running 25 degrees above the x axis, sheet B
in z = -0.25 x with its strands 25 degrees below it. Seen from above, A is in
front for x > 0 and B for x < 0, so the visible strand direction and colour
switch at x = 0 -- the interpenetration line the mass field is meant to hide.
A round clump of parallel strands along y stands apart at x = 1.6, for the
mass normal of a clump's silhouette and axis. Each prim's `displayColor` is the
per-strand colour the spike compares the mass colour against; the curves are
unbound, so they render the default grey.

Deterministic (no randomness): the strands are a fixed lattice.

    python3 scripts/gen_mass_spike.py > samples/mass_spike.usda
"""

import math

SPACING = 0.04  # between neighbouring strands, measured across them
WIDTH = 0.05  # wider than the spacing: neighbouring strands overlap, as hair does
TILT = 0.25  # dz/dx of each sheet's plane
ANGLE = math.radians(25.0)  # each sheet's strand direction, from the x axis
CLUMP_CENTRE = (1.6, 0.0)  # (x, z)
CLUMP_RADIUS = 0.25


def clip_line(px, py, dx, dy, lo=-1.0, hi=1.0):
    """The segment of the line p + t d inside the square [lo, hi]^2, or None."""
    t0, t1 = -1e9, 1e9
    for p, d in ((px, dx), (py, dy)):
        if abs(d) < 1e-12:
            if p < lo or p > hi:
                return None
            continue
        a, b = (lo - p) / d, (hi - p) / d
        t0, t1 = max(t0, min(a, b)), min(t1, max(a, b))
    if t1 - t0 < 1e-6:
        return None
    return (px + t0 * dx, py + t0 * dy), (px + t1 * dx, py + t1 * dy)


def sheet(sign):
    """Strands of one sheet as point lists: lines along the sheet's direction,
    spaced SPACING apart across it, clipped to the unit square, lifted onto the
    sheet's plane z = sign * TILT * x."""
    dx, dy = math.cos(ANGLE), sign * math.sin(ANGLE)
    nx, ny = -dy, dx  # across the strands
    strands = []
    n = int(math.ceil(1.5 / SPACING))
    for k in range(-n, n + 1):
        seg = clip_line(k * SPACING * nx, k * SPACING * ny, dx, dy)
        if seg is None:
            continue
        strands.append([(x, y, sign * TILT * x) for (x, y) in seg])
    return strands


def clump():
    """Parallel strands along y, hex-packed in a disc of the xz plane."""
    strands = []
    row = SPACING * math.sqrt(3.0) / 2.0
    j = -int(CLUMP_RADIUS / row) - 1
    while j * row <= CLUMP_RADIUS + row:
        offset = 0.5 * SPACING if j % 2 else 0.0
        i = -int(CLUMP_RADIUS / SPACING) - 1
        while i * SPACING <= CLUMP_RADIUS + SPACING:
            x, z = i * SPACING + offset, j * row
            if x * x + z * z <= CLUMP_RADIUS * CLUMP_RADIUS:
                cx, cz = CLUMP_CENTRE
                strands.append([(cx + x, -1.0, cz + z), (cx + x, 1.0, cz + z)])
            i += 1
        j += 1
    return strands


def fmt(v):
    return f"{v:.6g}"


def curves(name, strands, colour):
    counts = ", ".join(str(len(s)) for s in strands)
    points = ", ".join(
        f"({fmt(x)}, {fmt(y)}, {fmt(z)})" for s in strands for (x, y, z) in s
    )
    r, g, b = colour
    return f'''
    def BasisCurves "{name}"
    {{
        uniform token type = "linear"
        int[] curveVertexCounts = [{counts}]
        point3f[] points = [{points}]
        float[] widths = [{WIDTH}] (interpolation = "constant")
        color3f[] primvars:displayColor = [({r}, {g}, {b})] (interpolation = "constant")
    }}'''


SHEETS = [
    ("SheetA", sheet(+1.0), (0.8, 0.1, 0.1)),
    ("SheetB", sheet(-1.0), (0.1, 0.2, 0.8)),
    ("Clump", clump(), (0.1, 0.7, 0.2)),
]

print(f'''#usda 1.0
(
    doc = """curve-mass-field spike: two sheets of strands crossing along x = 0,
    and a round clump at x = 1.6, seen from above. Generated by
    scripts/gen_mass_spike.py; measured by the mass_spike example:

      cargo run --release -p crust-render --example mass_spike -- samples/mass_spike.usda
    """
    defaultPrim = "World"
    upAxis = "Y"
)

def Xform "World"
{{
    def Camera "Camera"
    {{
        float focalLength = 50
        float horizontalAperture = 36
        float verticalAperture = 24
        double3 xformOp:translate = (0.5, 0, 12)
        uniform token[] xformOpOrder = ["xformOp:translate"]
    }}

    def DomeLight "Sky"
    {{
        float inputs:intensity = 1
    }}

    def DistantLight "Key"
    {{
        float inputs:intensity = 2
        float inputs:angle = 2
        float3 xformOp:rotateXYZ = (-35, 25, 0)
        uniform token[] xformOpOrder = ["xformOp:rotateXYZ"]
    }}
{"".join(curves(n, s, c) for n, s, c in SHEETS)}
}}''')
