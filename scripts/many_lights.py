#!/usr/bin/env python3
"""Writes samples/many_lights.usda: the light-tree sample.

256 small UsdLux lights over a floor with low walls, chosen so that flux
alone is a poor guide to which light lights a point:
  - 160 sphere lights on a jittered grid, at heights from 0.4 to 6;
  - 80 one-sided rect panels, half facing the floor and half the sky (a
    panel facing up lights nothing the camera sees but the walls' tops);
  - 16 narrow spots (rect lights with a 10 degree ShapingAPI cone).
Intensities spread over two decades; `normalize` is on, so intensity is
proportional to power. A faint dome keeps the infinite-light share in play.

The positions come from a fixed LCG, so rerunning this rewrites the same
file: `python3 scripts/many_lights.py > samples/many_lights.usda`.
"""


class Lcg:
    def __init__(self, seed):
        self.state = seed

    def next(self):
        self.state = (self.state * 6364136223846793005 + 1442695040888963407) % (1 << 64)
        return (self.state >> 40) / float(1 << 24)


def f(x):
    return f"{x:.4g}"


def main():
    rng = Lcg(20261015)
    out = []
    w = out.append
    w('#usda 1.0')
    w('(')
    w('    doc = """Many lights: the scene a light BVH is for.')
    w('')
    w('    256 small lights over a 40 m floor with low walls. Spheres at mixed')
    w('    heights, one-sided panels facing down and up, and narrow spots, with')
    w('    intensities over two decades. Generated by scripts/many_lights.py."""')
    w('    defaultPrim = "World"')
    w('    upAxis = "Y"')
    w(')')
    w('')
    w('def Xform "World"')
    w('{')
    w('    def Camera "Cam"')
    w('    {')
    w('        float focalLength = 20')
    w('        float horizontalAperture = 36')
    w('        double3 xformOp:translate = (0, 14, 26)')
    w('        float xformOp:rotateX = -30')
    w('        uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:rotateX"]')
    w('    }')
    w('')
    w('    def Mesh "Floor"')
    w('    {')
    w('        uniform token subdivisionScheme = "none"')
    w('        int[] faceVertexCounts = [4]')
    w('        int[] faceVertexIndices = [0, 1, 2, 3]')
    w('        point3f[] points = [(-20, 0, -20), (-20, 0, 20), (20, 0, 20), (20, 0, -20)]')
    w('    }')
    # Low walls: a few long, thin boxes that shadow parts of the floor.
    for i, (x, z, sx, sz) in enumerate(
        [(-8, -4, 10, 0.4), (6, 3, 0.4, 12), (0, 10, 14, 0.4), (-12, 8, 0.4, 8), (12, -10, 8, 0.4)]
    ):
        w('')
        w(f'    def Cube "Wall{i}"')
        w('    {')
        w('        double size = 1')
        w(f'        double3 xformOp:translate = ({f(x)}, 1, {f(z)})')
        w(f'        float3 xformOp:scale = ({f(sx)}, 2, {f(sz)})')
        w('        uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:scale"]')
        w('    }')
    # 160 spheres on a jittered 16 x 10 grid.
    for k in range(160):
        gx, gz = k % 16, k // 16
        x = -19 + 38 * (gx + rng.next()) / 16
        z = -19 + 38 * (gz + rng.next()) / 10
        y = 0.4 + 5.6 * rng.next()
        intensity = 2 * 10 ** (2 * rng.next())
        w('')
        w(f'    def SphereLight "Sphere{k:03d}"')
        w('    {')
        w('        float inputs:radius = 0.08')
        w('        bool inputs:normalize = 1')
        w(f'        float inputs:intensity = {f(intensity)}')
        w(f'        double3 xformOp:translate = ({f(x)}, {f(y)}, {f(z)})')
        w('        uniform token[] xformOpOrder = ["xformOp:translate"]')
        w('    }')
    # 80 panels: even ones face the floor, odd ones the sky.
    for k in range(80):
        x = -19 + 38 * rng.next()
        z = -19 + 38 * rng.next()
        y = 2.5 + 4 * rng.next()
        yaw = 360 * rng.next()
        intensity = 1 * 10 ** (2 * rng.next())
        pitch = -90 if k % 2 == 0 else 90
        w('')
        w(f'    def RectLight "Panel{k:03d}"')
        w('    {')
        w('        float inputs:width = 0.6')
        w('        float inputs:height = 0.3')
        w('        bool inputs:normalize = 1')
        w(f'        float inputs:intensity = {f(intensity)}')
        w(f'        double3 xformOp:translate = ({f(x)}, {f(y)}, {f(z)})')
        w(f'        float xformOp:rotateY = {f(yaw)}')
        w(f'        float xformOp:rotateX = {pitch}')
        w('        uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:rotateY", "xformOp:rotateX"]')
        w('    }')
    # 16 narrow spots pointing down at angles.
    for k in range(16):
        x = -16 + 32 * rng.next()
        z = -16 + 32 * rng.next()
        tilt = -90 + 30 * (rng.next() - 0.5)
        yaw = 360 * rng.next()
        intensity = 40 * 10 ** (rng.next())
        w('')
        w(f'    def RectLight "Spot{k:02d}" (')
        w('        prepend apiSchemas = ["ShapingAPI"]')
        w('    )')
        w('    {')
        w('        float inputs:width = 0.2')
        w('        float inputs:height = 0.2')
        w('        bool inputs:normalize = 1')
        w(f'        float inputs:intensity = {f(intensity)}')
        w('        float inputs:shaping:cone:angle = 10')
        w('        float inputs:shaping:cone:softness = 0.2')
        w(f'        double3 xformOp:translate = ({f(x)}, 7, {f(z)})')
        w(f'        float xformOp:rotateY = {f(yaw)}')
        w(f'        float xformOp:rotateX = {f(tilt)}')
        w('        uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:rotateY", "xformOp:rotateX"]')
        w('    }')
    w('')
    w('    def DomeLight "Fill"')
    w('    {')
    w('        float inputs:intensity = 0.01')
    w('    }')
    w('}')
    w('')
    w('def Scope "Render"')
    w('{')
    w('    def RenderSettings "settings"')
    w('    {')
    w('        int2 resolution = (480, 270)')
    w('        int crust:samplesPerPixel = 64')
    w('        int crust:maxDepth = 4')
    w('        int crust:frame = 0')
    w('    }')
    w('}')
    print("\n".join(out))


if __name__ == "__main__":
    main()
